# -*- coding: utf-8 -*-
"""
WinCraft Studio — Standalone mrp.bom / mrp.bom.line extension.

WincraftWindowBomBuilder (wincraft_bom_builder.py) generates a per-window
cut-list BOM and needs a handful of fields that aren't part of stock Odoo
`mrp`: a flag marking a BOM as a per-window custom build, plus cut
dimensions and a component category on each line.

These same field names already exist in the separate, private
`fenestriflow` module (fenestriflow/models/mrp_bom.py and mrp_bom_line.py)
for its own CSV/order-entry pipeline. wincraft_studio no longer depends on
that module (see CHANGELOG), so the small subset it actually uses is
defined here instead — duplicated on purpose, not imported across module
boundaries, so wincraft_studio installs and runs standalone. The selection
values are kept identical to fenestriflow's so the two coexist cleanly if
both happen to be installed together (Odoo simply merges same-named,
same-typed fields from multiple `_inherit` extensions).
"""
from odoo import models, fields

COMPONENT_TYPE_SELECTION = [
    ('frame', 'Outer Frame'),
    ('sash', 'Sash Frame'),
    ('glass', 'Glass'),
    ('bead', 'Glazing Bead'),
    ('gasket', 'Gasket / Seal'),
    ('reinforcement', 'Reinforcement'),
    ('hardware', 'Hardware'),
    ('seal', 'Weatherseal'),
    ('mullion', 'Mullion / Transom'),
    ('spacer', 'Spacer'),
    ('addon', 'Add-on / Accessory'),
    ('paint', 'Paint'),
    ('other', 'Other'),
]


class MrpBomCutlistExt(models.Model):
    _inherit = 'mrp.bom'

    is_custom = fields.Boolean(
        string='Custom BOM',
        default=False,
        help='Marks a per-window BOM generated by the WinCraft Studio designer '
             '("Generate BOM"), as opposed to a shared master/template BOM.',
    )


class MrpBomLineCutlistExt(models.Model):
    _inherit = 'mrp.bom.line'

    length_mm = fields.Float(
        string='Length (mm)',
        digits=(12, 1),
        help='Cut length in millimetres.',
    )
    width_mm = fields.Float(
        string='Width (mm)',
        digits=(12, 1),
        help='Cut width in millimetres (for sheet materials like glass).',
    )
    component_type = fields.Selection(
        selection=COMPONENT_TYPE_SELECTION,
        string='Component Type',
        help='BOM component category for grouping and reporting.',
    )
    x_notes = fields.Char(
        string='Notes',
        help='Free-form notes applied to this BOM line.',
    )
